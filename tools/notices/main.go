// Command notices writes THIRD_PARTY_NOTICES: the license and notice files of every module
// compiled into the montecarlo binary, which every release archive has to carry alongside its
// own LICENSE. cmd/montecarlo runs it from go generate, so it lists that package's dependencies
// from the module cache of the current go.mod.
package main

import (
	"bufio"
	"bytes"
	"flag"
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"regexp"
	"sort"
	"strings"
)

// The operating systems the binary is built for, kept in step with the release targets. A
// dependency imported under a build constraint is compiled in on some of them only, so the
// list is the union across them.
var goos = []string{"darwin", "linux", "windows"}

var noticeFile = regexp.MustCompile(`(?i)^(licen[cs]e|copying|notice|patents)([.-].*)?$`)

const header = `Third-party notices for mc-cli

The montecarlo release binaries include the Go modules below. Each module's license and notice
files follow verbatim. The source code of every module is available at the version listed,
from the Go module proxy: https://proxy.golang.org/<module>/@v/<version>.zip

Generated by go generate ./... from tools/notices. Do not edit by hand.
`

type module struct{ path, version, dir string }

func main() {
	out := flag.String("o", "THIRD_PARTY_NOTICES", "file to write")
	flag.Parse()
	if err := run(*out); err != nil {
		fmt.Fprintln(os.Stderr, "notices:", err)
		os.Exit(1)
	}
}

func run(out string) error {
	mods, err := modules()
	if err != nil {
		return err
	}
	var b strings.Builder
	b.WriteString(header)
	for _, m := range mods {
		files, err := noticeFiles(m.dir)
		if err != nil {
			return err
		}
		if len(files) == 0 {
			return fmt.Errorf("%s %s has no license file in %s", m.path, m.version, m.dir)
		}
		fmt.Fprintf(&b, "\n%s\n%s %s\n", strings.Repeat("=", 80), m.path, m.version)
		for _, name := range files {
			text, err := os.ReadFile(filepath.Join(m.dir, name))
			if err != nil {
				return err
			}
			fmt.Fprintf(&b, "%s\n%s\n\n%s\n", strings.Repeat("-", 80), name, bytes.TrimRight(text, "\n"))
		}
	}
	return os.WriteFile(out, []byte(b.String()), 0o644)
}

// modules lists the non-main modules of the packages compiled into the binary, sorted by path.
func modules() ([]module, error) {
	seen := map[string]module{}
	for _, target := range goos {
		cmd := exec.Command("go", "list", "-deps", "-f",
			`{{with .Module}}{{if not .Main}}{{.Path}}{{"\t"}}{{.Version}}{{"\t"}}{{.Dir}}{{end}}{{end}}`, ".")
		cmd.Env = append(os.Environ(), "GOOS="+target, "CGO_ENABLED=0")
		cmd.Stderr = os.Stderr
		out, err := cmd.Output()
		if err != nil {
			return nil, fmt.Errorf("go list for GOOS=%s: %w", target, err)
		}
		sc := bufio.NewScanner(bytes.NewReader(out))
		for sc.Scan() {
			f := strings.Split(sc.Text(), "\t")
			if len(f) != 3 {
				continue
			}
			if f[2] == "" {
				return nil, fmt.Errorf("%s %s is not in the module cache", f[0], f[1])
			}
			seen[f[0]] = module{path: f[0], version: f[1], dir: f[2]}
		}
	}
	mods := make([]module, 0, len(seen))
	for _, m := range seen {
		mods = append(mods, m)
	}
	sort.Slice(mods, func(i, j int) bool { return mods[i].path < mods[j].path })
	return mods, nil
}

// noticeFiles returns the license and notice files at the root of dir, sorted by name.
func noticeFiles(dir string) ([]string, error) {
	entries, err := os.ReadDir(dir)
	if err != nil {
		return nil, err
	}
	var names []string
	for _, e := range entries {
		if !e.IsDir() && noticeFile.MatchString(e.Name()) {
			names = append(names, e.Name())
		}
	}
	sort.Strings(names)
	return names, nil
}
